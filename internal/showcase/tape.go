package showcase

import (
	"fmt"
	"path/filepath"
	"strings"
	"time"
)

// RenderOpts supplies what the tape needs but the manifest cannot know:
// where the binary and clean config root live on *this* machine right now.
type RenderOpts struct {
	// MilkPath is the absolute path of the milk binary to launch.
	MilkPath string
	// ConfigRoot is the clean state root for the recording pass.
	ConfigRoot string
	// SeedRoot is the pristine master the launch re-copies into ConfigRoot
	// before milk starts ("" = no re-seed: the launch uses ConfigRoot as
	// it is). Both roots persist beside the workdir — a temp root died
	// with the record run and every later render booted config-less milk.
	SeedRoot string
	// Workdir is the absolute directory the recorded shell starts in.
	Workdir string
}

// RenderTape turns a calibrated manifest into a vhs tape: the same steps
// the calibration sent, separated by sleeps derived from measured
// durations. One source, two passes — the tape cannot drift from the
// waits because both come from the same beat list.
func RenderTape(m *Manifest, res Result, opts RenderOpts) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# GENERATED by `task showcase:record` from %s — edit the manifest, not this file.\n", m.Name)
	fmt.Fprintf(&b, "# Beats and sleeps are calibrated against a live run; regenerate after changing the manifest.\n")
	// The tape records mp4, not gif: vhs's gif path is one ffmpeg pass whose
	// palettegen+paletteuse chain buffers every frame until the palette is
	// ready — O(duration) RAM, OOM-killed on long full-width runs (which vhs
	// reports as success). The mp4 encoder streams; the runner derives the
	// gif from it two-pass (see GIFTwoPass).
	fmt.Fprintf(&b, "Output %s\n", MP4Path(m.Output))
	fmt.Fprintf(&b, "\nSet Shell \"bash\"\n")
	fmt.Fprintf(&b, "Set Width %d\n", m.Terminal.Width)
	fmt.Fprintf(&b, "Set Height %d\n", m.Terminal.Height)
	if m.Terminal.FontSize > 0 {
		fmt.Fprintf(&b, "Set FontSize %d\n", m.Terminal.FontSize)
	}
	if m.Terminal.Theme != "" {
		fmt.Fprintf(&b, "Set Theme \"%s\"\n", m.Terminal.Theme)
	}
	if m.Terminal.TypingSpeed != "" {
		fmt.Fprintf(&b, "Set TypingSpeed %s\n", m.Terminal.TypingSpeed)
	}
	if m.Terminal.PlaybackSpeed > 0 {
		fmt.Fprintf(&b, "Set PlaybackSpeed %g\n", m.Terminal.PlaybackSpeed)
	}

	// Launch: restore the pristine record root from its seed master, then
	// cd + config root + the binary + the manifest's launch words. The
	// re-seed runs on *every* render: the root is mutated by each one, and
	// the calibration measured a fresh root — without the copy, the second
	// render starts from leftover sessions, panels and state (and a deleted
	// root makes milk boot config-less: recordings of it complaining about
	// a missing primary agent instead of working). Everything absolute, so
	// the tape replays from any directory.
	launch := ""
	if opts.SeedRoot != "" {
		launch = fmt.Sprintf("rm -rf %s && cp -r %s %s && ",
			shellQuote(opts.ConfigRoot), shellQuote(opts.SeedRoot), shellQuote(opts.ConfigRoot))
	}
	launch += fmt.Sprintf("cd %s && MILK_CONFIG_ROOT=%s %s",
		shellQuote(opts.Workdir), shellQuote(opts.ConfigRoot), shellQuote(opts.MilkPath))
	if m.Launch != "" {
		launch += " " + strings.TrimSpace(m.Launch)
	}
	b.WriteString("\n# ── launch ──────────────────────────────────────────────────────\n")
	// The recording is only useful from milk's TUI on: the shell prompt,
	// the typed launch line and cold boot are setup, not content — hide
	// them and reveal on the first frame milk owns (the boot Sleep is the
	// measured launch duration, so Show lands once milk is up). Type@0ms:
	// a hidden line's typing animation would only cost wall time.
	b.WriteString("Hide\n")
	fmt.Fprintf(&b, "Type@0ms %s\n", vhsQuote(launch))
	b.WriteString("Enter\n")
	fmt.Fprintf(&b, "Sleep %s\n", sleepDuration(res.LaunchElapsed, m.Margin, m.Base))
	b.WriteString("Show\n")

	byID := map[string]BeatTiming{}
	for _, t := range res.Timings {
		byID[t.ID] = t
	}

	for bi, beat := range m.Beats {
		timing, ok := byID[beat.ID]
		b.WriteString("\n# ── ")
		b.WriteString(beat.ID)
		if beat.Note != "" {
			b.WriteString(": ")
			b.WriteString(strings.ReplaceAll(beat.Note, "\n", " "))
		}
		b.WriteString(" ──\n")
		if ok && timing.Skipped {
			fmt.Fprintf(&b, "# skipped in calibration (skip_if matched) — nothing to record\n")
			continue
		}
		// Each wait's measured time is emitted as an inline Sleep at the
		// step where it happened — never lumped at the beat's end: a
		// keypress must replay in the same gap it had in calibration
		// (typing the next command 0ms after the Enter that starts a model
		// turn, or the flyover-accept Enter before the picker rendered,
		// replays narration that never happened). Sub-measure steps fold
		// into the trailing sleep — total replay time stays
		// margin*elapsed+base, relocated rather than added.
		var slowSteps time.Duration
		for si, step := range beat.Steps {
			writeStep(&b, step, res.Vars)
			if ok && si < len(timing.Steps) {
				d := timing.Steps[si]
				if secs := d.Seconds() * m.Margin; secs >= minStepSleep {
					fmt.Fprintf(&b, "Sleep %.1fs\n", secs)
					slowSteps += d
				}
			}
		}
		if ok {
			fmt.Fprintf(&b, "Sleep %s\n", sleepDuration(timing.Elapsed-slowSteps, m.Margin, m.Base))
		}
		// Between beats: reading room before the next command types —
		// calibration measures when a wait completed, not when a viewer
		// has read the result, and without this the next command starts
		// typing almost on the heels of the previous one (base is only
		// 0.4s). None after the last beat: the hold covers the ending.
		if m.Between != "" && bi < len(m.Beats)-1 {
			b.WriteString("# pause between beats — room to read the result\n")
			fmt.Fprintf(&b, "Sleep %s\n", m.Between)
		}
	}
	// Hold the final view: the last beat's sleep lands the last wait, and a
	// tape that ends right there cuts the finished composition — the frame
	// the recording exists to show — a few stable seconds before the loop.
	b.WriteString("\n# hold the final view — the last screen stays a few seconds before the loop\n")
	b.WriteString("Sleep 5s\n")
	return b.String()
}

// minStepSleep is the smallest per-step Sleep the tape emits (seconds,
// after margin): a wait short enough to vanish under typing-speed latency
// needs no pause — the next keystroke arrives naturally — while every real
// wait gets its own visible, faithful gap.
const minStepSleep = 0.3

// writeStep emits the vhs commands for one calibrated step. Waits and
// extracts have no vhs counterpart — their cost is inside the beat's sleep.
func writeStep(b *strings.Builder, step Step, vars map[string]string) {
	if step.Clear {
		b.WriteString("Repeat 120 {\n  Backspace\n}\n")
	}
	if step.Type != "" {
		fmt.Fprintf(b, "Type %s\n", vhsQuote(Interpolate(step.Type, vars)))
	}
	if step.Key != "" {
		b.WriteString(step.Key)
		b.WriteString("\n")
	}
	if step.Wait != "" {
		fmt.Fprintf(b, "# wait: %s\n", step.Wait)
	}
	if step.WaitAbsent != "" {
		fmt.Fprintf(b, "# until gone: %s\n", step.WaitAbsent)
	}
	if step.Extract != nil {
		fmt.Fprintf(b, "# extracted {{%s}}\n", step.Extract.Name)
	}
}

// sleepDuration is the recording's rest after a measured stretch.
func sleepDuration(elapsed time.Duration, margin, base float64) string {
	secs := elapsed.Seconds()*margin + base
	if secs < base+0.1 {
		secs = base + 0.1
	}
	return fmt.Sprintf("%.1fs", secs)
}

// vhsQuote renders text as a vhs Type argument. vhs's tokenizer has no
// \" escape inside double quotes (a quoted prompt like `titled "X"` parses
// as garbage — hit while recording the plot prompts), so text containing a
// double quote switches to vhs's backtick raw-string form, which takes
// quotes literally. Backtick inside backtick is the one unsupported shape
// (no prompt needs it; both delimiters would be ambiguous anyway).
func vhsQuote(s string) string {
	if strings.Contains(s, `"`) && !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

// shellQuote single-quotes a path for the launch line.
func shellQuote(p string) string {
	return "'" + strings.ReplaceAll(p, `'`, `'\''`) + "'"
}

// TapePath resolves the manifest's tape path relative to its own directory.
func (m *Manifest) TapePath(manifestPath string) string {
	tape := m.Tape
	if tape == "" {
		tape = "demo.tape"
	}
	if filepath.IsAbs(tape) {
		return tape
	}
	return filepath.Join(filepath.Dir(manifestPath), tape)
}
