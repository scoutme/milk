package showcase

import (
	"fmt"
	"path/filepath"
	"strings"
	"time"
)

// RenderOpts supplies what the tape needs but the manifest cannot know:
// where the binary and clean config root live on *this* machine right now.
type RenderOpts struct {
	// MilkPath is the absolute path of the milk binary to launch.
	MilkPath string
	// ConfigRoot is the clean state root for the recording pass.
	ConfigRoot string
	// Workdir is the absolute directory the recorded shell starts in.
	Workdir string
}

// RenderTape turns a calibrated manifest into a vhs tape: the same steps
// the calibration sent, separated by sleeps derived from measured
// durations. One source, two passes — the tape cannot drift from the
// waits because both come from the same beat list.
func RenderTape(m *Manifest, res Result, opts RenderOpts) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# GENERATED by `task showcase:record` from %s — edit the manifest, not this file.\n", m.Name)
	fmt.Fprintf(&b, "# Beats and sleeps are calibrated against a live run; regenerate after changing the manifest.\n")
	fmt.Fprintf(&b, "Output %s\n", m.Output)
	fmt.Fprintf(&b, "\nSet Shell \"bash\"\n")
	fmt.Fprintf(&b, "Set Width %d\n", m.Terminal.Width)
	fmt.Fprintf(&b, "Set Height %d\n", m.Terminal.Height)
	if m.Terminal.FontSize > 0 {
		fmt.Fprintf(&b, "Set FontSize %d\n", m.Terminal.FontSize)
	}
	if m.Terminal.Theme != "" {
		fmt.Fprintf(&b, "Set Theme \"%s\"\n", m.Terminal.Theme)
	}
	if m.Terminal.TypingSpeed != "" {
		fmt.Fprintf(&b, "Set TypingSpeed %s\n", m.Terminal.TypingSpeed)
	}
	if m.Terminal.PlaybackSpeed > 0 {
		fmt.Fprintf(&b, "Set PlaybackSpeed %g\n", m.Terminal.PlaybackSpeed)
	}

	// Launch: cd + clean config root + the binary + the manifest's launch
	// words. Everything absolute, so the tape replays from any directory.
	launch := fmt.Sprintf("cd %s && MILK_CONFIG_ROOT=%s %s",
		shellQuote(opts.Workdir), shellQuote(opts.ConfigRoot), shellQuote(opts.MilkPath))
	if m.Launch != "" {
		launch += " " + strings.TrimSpace(m.Launch)
	}
	b.WriteString("\n# ── launch ──────────────────────────────────────────────────────\n")
	fmt.Fprintf(&b, "Type %s\n", vhsQuote(launch))
	b.WriteString("Enter\n")
	fmt.Fprintf(&b, "Sleep %s\n", sleepDuration(res.LaunchElapsed, m.Margin, m.Base))

	byID := map[string]BeatTiming{}
	for _, t := range res.Timings {
		byID[t.ID] = t
	}

	for _, beat := range m.Beats {
		timing, ok := byID[beat.ID]
		b.WriteString("\n# ── ")
		b.WriteString(beat.ID)
		if beat.Note != "" {
			b.WriteString(": ")
			b.WriteString(strings.ReplaceAll(beat.Note, "\n", " "))
		}
		b.WriteString(" ──\n")
		if ok && timing.Skipped {
			fmt.Fprintf(&b, "# skipped in calibration (skip_if matched) — nothing to record\n")
			continue
		}
		for _, step := range beat.Steps {
			writeStep(&b, step, res.Vars)
		}
		if ok {
			fmt.Fprintf(&b, "Sleep %s\n", sleepDuration(timing.Elapsed, m.Margin, m.Base))
		}
	}
	return b.String()
}

// writeStep emits the vhs commands for one calibrated step. Waits and
// extracts have no vhs counterpart — their cost is inside the beat's sleep.
func writeStep(b *strings.Builder, step Step, vars map[string]string) {
	if step.Clear {
		b.WriteString("Repeat 120 {\n  Backspace\n}\n")
	}
	if step.Type != "" {
		fmt.Fprintf(b, "Type %s\n", vhsQuote(Interpolate(step.Type, vars)))
	}
	if step.Key != "" {
		b.WriteString(step.Key)
		b.WriteString("\n")
	}
	if step.Wait != "" {
		fmt.Fprintf(b, "# wait: %s\n", step.Wait)
	}
	if step.WaitAbsent != "" {
		fmt.Fprintf(b, "# until gone: %s\n", step.WaitAbsent)
	}
	if step.Extract != nil {
		fmt.Fprintf(b, "# extracted {{%s}}\n", step.Extract.Name)
	}
}

// sleepDuration is the recording's rest after a measured stretch.
func sleepDuration(elapsed time.Duration, margin, base float64) string {
	secs := elapsed.Seconds()*margin + base
	if secs < base+0.1 {
		secs = base + 0.1
	}
	return fmt.Sprintf("%.1fs", secs)
}

// vhsQuote renders text as a vhs Type argument: double-quoted, with the
// escapes vhs (a shell-ish tokenizer) treats as significant. The texts are
// literal TUI input — never shell-evaluated — so $ and backticks stay as-is.
func vhsQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

// shellQuote single-quotes a path for the launch line.
func shellQuote(p string) string {
	return "'" + strings.ReplaceAll(p, `'`, `'\''`) + "'"
}

// TapePath resolves the manifest's tape path relative to its own directory.
func (m *Manifest) TapePath(manifestPath string) string {
	tape := m.Tape
	if tape == "" {
		tape = "demo.tape"
	}
	if filepath.IsAbs(tape) {
		return tape
	}
	return filepath.Join(filepath.Dir(manifestPath), tape)
}
