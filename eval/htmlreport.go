// ---------------------------------------------------------------------------
// HTML report generator
// ---------------------------------------------------------------------------

// esc escapes text for interpolation into HTML element/attribute content.
// Every dynamic string in this file goes through it — scenario names, agent
// names, criterion names, judge reasoning, tool lists, error strings — so a
// results file containing markup (adversarial output, `<script>` in a prompt)
// renders inert instead of executing.
func esc(s string) string { return html.EscapeString(s) }

// GenerateHTML produces a self-contained HTML report: the same sections as
// GenerateReport (per-scenario score/metrics/tool/budget tables, multi-turn
// cache, repetition statistics, aggregate + winner) rendered as real tables,
// with one inline stylesheet and no external assets — a single file that can
// be opened via file:// or attached anywhere. Score cells come from the shared
// buildScoreGrid, so ERR/—/* semantics cannot drift from the text report.
func GenerateHTML(scenarioResults []ScenarioResult) string {
	agentNames := collectAgentNames(scenarioResults)
	repTotals := repCounts(scenarioResults)

	var b strings.Builder
	b.WriteString("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
	b.WriteString("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
	b.WriteString("<title>milk eval report</title>\n<style>\n")
	b.WriteString(htmlReportCSS)
	b.WriteString("</style>\n</head>\n<body>\n")

	// --- Header + meta ---
	categories := map[string]bool{}
	for _, sr := range scenarioResults {
		categories[sr.Category] = true
	}
	b.WriteString("<header>\n<h1>milk eval report</h1>\n<p class=\"meta\">")
	b.WriteString(fmt.Sprintf("%d scenario(s) · %d categor%s · %d agent(s) · generated %s</p>\n",
		len(scenarioResults), len(categories), pluralY(len(categories)),
		len(agentNames), esc(time.Now().Format("2006-01-02 15:04:05 MST"))))
	b.WriteString("</header>\n")

	// --- Table of contents ---
	if len(scenarioResults) > 0 {
		b.WriteString("<nav class=\"toc\"><strong>Scenarios</strong><ol>\n")
		for i, sr := range scenarioResults {
			b.WriteString(fmt.Sprintf("<li><a href=\"#%s\">%s</a></li>\n",
				scenarioSlug(sr, repTotals, i), esc(scenarioTitle(sr, repTotals))))
		}
		b.WriteString("</ol></nav>\n")
	}

	// --- Per-scenario sections ---
	for i, sr := range scenarioResults {
		htmlScenarioSection(&b, sr, agentNames, repTotals, i)
	}

	// --- Repetition statistics (mean ± sd across runs) ---
	if maxRepCount(repTotals) > 1 {
		htmlRepetitionSection(&b, scenarioResults, agentNames)
	}

	// --- Aggregate section ---
	htmlAggregateSection(&b, scenarioResults, agentNames)

	b.WriteString("<footer>generated by <code>milk eval report --html</code> · source data: results.json in the same directory</footer>\n")
	b.WriteString("</body>\n</html>\n")
	return b.String()
}

func pluralY(n int) string {
	if n == 1 {
		return "y"
	}
	return "ies"
}

// scenarioTitle mirrors GenerateReport's per-entry title (rep label included).
func scenarioTitle(sr ScenarioResult, repTotals map[string]int) string {
	if n := repTotals[sr.ScenarioName]; n > 1 && sr.Repetition > 0 {
		return fmt.Sprintf("%s (run %d/%d)", sr.ScenarioName, sr.Repetition, n)
	}
	return sr.ScenarioName
}

// scenarioSlug builds a stable anchor id; the index suffix keeps duplicates
// (same scenario, several repetitions) unique without a map.
func scenarioSlug(sr ScenarioResult, repTotals map[string]int, idx int) string {
	var b strings.Builder
	for _, r := range strings.ToLower(scenarioTitle(sr, repTotals)) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	s := strings.Trim(b.String(), "-")
	if s == "" {
		s = "scenario"
	}
	return fmt.Sprintf("%s-%d", s, idx)
}

// ---------------------------------------------------------------------------
// Scenario section
// ---------------------------------------------------------------------------

func htmlScenarioSection(b *strings.Builder, sr ScenarioResult, agentNames []string, repTotals map[string]int, idx int) {
	fmt.Fprintf(b, "<section id=\"%s\">\n", scenarioSlug(sr, repTotals, idx))
	fmt.Fprintf(b, "<h2>%s</h2>\n", esc(scenarioTitle(sr, repTotals)))
	b.WriteString("<p class=\"chips\">")
	fmt.Fprintf(b, "<span>%s</span><span>%s</span>\n", esc(sr.Category), esc(sr.Difficulty))
	b.WriteString("</p>\n")

	if w := pickWinner(sr); w != "" {
		fmt.Fprintf(b, "<p><span class=\"winner\">Winner: %s</span></p>\n", esc(w))
	}

	// --- Score table (shared grid with the text report) ---
	grid := buildScoreGrid(sr, agentNames)
	if len(grid.criteria) > 0 {
		b.WriteString("<div class=\"tblwrap\"><table class=\"scores\">\n<thead><tr><th></th>")
		for _, name := range agentNames {
			fmt.Fprintf(b, "<th>%s</th>", esc(name))
		}
		b.WriteString("</tr></thead>\n<tbody>\n")
		for _, c := range grid.criteria {
			fmt.Fprintf(b, "<tr><th scope=\"row\">%s</th>", esc(c))
			for _, name := range agentNames {
				cell := grid.cells[strings.ToLower(c)][name]
				b.WriteString("<td" + cellClass(cell) + ">" + esc(cell) + "</td>")
			}
			b.WriteString("</tr>\n")
		}
		b.WriteString("<tr class=\"weighted\"><th scope=\"row\">Weighted Score</th>")
		for _, name := range agentNames {
			cell := grid.weighted[name]
			b.WriteString("<td" + cellClass(cell) + ">" + esc(cell) + "</td>")
		}
		b.WriteString("</tr>\n</tbody></table></div>\n")
	}

	// --- Judge warnings (why any ERR / * above) ---
	for _, name := range agentNames {
		ar, ok := sr.AgentResults[name]
		if !ok {
			continue
		}
		if ar.JudgeError != "" {
			fmt.Fprintf(b, "<p class=\"warn\">⚠ judging failed for %s: %s</p>\n",
				esc(name), esc(ar.JudgeError))
		}
		if len(ar.MissingCriteria) > 0 {
			fmt.Fprintf(b, "<p class=\"warn\">⚠ partial rubric for %s: judge returned no score for %s — the weighted score (*) covers the remaining criteria only</p>\n",
				esc(name), esc(strings.Join(ar.MissingCriteria, ", ")))
		}
	}

	// --- Metrics table ---
	htmlMetricsTable(b, sr, agentNames)

	// --- Tool-call lists (behind the count) ---
	for _, name := range agentNames {
		ar, ok := sr.AgentResults[name]
		if !ok {
			continue
		}
		var names []string
		for _, r := range ar.RunResults {
			for _, tc := range r.ToolCalls {
				names = append(names, tc.Name)
			}
		}
		if len(names) == 0 {
			continue
		}
		list := strings.Join(names, ", ")
		const maxLen = 160
		if len(list) > maxLen {
			list = list[:maxLen] + "…"
		}
		fmt.Fprintf(b, "<details><summary>Tools [%s] (%d)</summary><code>%s</code></details>\n",
			esc(name), len(names), esc(list))
	}

	// --- Per-turn cache breakdown (multi-turn scenarios) ---
	maxTurns := 0
	for _, ar := range sr.AgentResults {
		if len(ar.RunResults) > maxTurns {
			maxTurns = len(ar.RunResults)
		}
	}
	if maxTurns >= 2 {
		htmlPerTurnCacheTable(b, sr, agentNames, maxTurns)
	}

	// --- Judge reasoning (per agent, collapsed) ---
	for _, name := range agentNames {
		ar, ok := sr.AgentResults[name]
		if !ok || len(ar.Scores) == 0 {
			continue
		}
		fmt.Fprintf(b, "<details><summary>Judgment reasoning [%s]</summary><ul>\n", esc(name))
		for _, s := range ar.Scores {
			fmt.Fprintf(b, "<li><strong>%s = %.1f</strong>: %s</li>\n",
				esc(s.Criterion), s.Score, esc(s.Reasoning))
		}
		b.WriteString("</ul></details>\n")
	}

	b.WriteString("</section>\n")
}

// cellClass maps a score-grid cell to its CSS class: judge errors red,
// judge gaps muted, real scores neutral.
func cellClass(cell string) string {
	switch cell {
	case "ERR":
		return " class=\"err\""
	case "—", "-":
		return " class=\"gap\""
	default:
		return ""
	}
}

// htmlMetricsRow appends one label + per-agent value row.
func htmlMetricsRow(b *strings.Builder, label string, agentNames []string, value func(name string) string) {
	fmt.Fprintf(b, "<tr><th scope=\"row\">%s</th>", esc(label))
	for _, name := range agentNames {
		fmt.Fprintf(b, "<td>%s</td>", esc(value(name)))
	}
	b.WriteString("</tr>\n")
}

// htmlMetricsTable renders tokens, cache, hit rate, cost, duration, tools and
// the budget verdict — the same rows as buildMetricsTable.
func htmlMetricsTable(b *strings.Builder, sr ScenarioResult, agentNames []string) {
	type totals struct {
		input, output, cacheCreate, cacheRead int64
		cost                                  float64
		duration                              time.Duration
		toolCalls                             int
	}
	agentTotals := map[string]totals{}
	hasBudget := false
	for _, name := range agentNames {
		ar, ok := sr.AgentResults[name]
		if !ok {
			agentTotals[name] = totals{}
			continue
		}
		var t totals
		for _, r := range ar.RunResults {
			t.input += r.Tokens.InputTokens
			t.output += r.Tokens.OutputTokens
			t.cacheCreate += r.Tokens.CacheCreate
			t.cacheRead += r.Tokens.CacheRead
			t.cost += r.CostUSD
			t.duration += r.Duration
			t.toolCalls += len(r.ToolCalls)
		}
		agentTotals[name] = t
		if ar.BudgetResult != nil {
			hasBudget = true
		}
	}

	b.WriteString("<div class=\"tblwrap\"><table class=\"metrics\">\n<thead><tr><th></th>")
	for _, name := range agentNames {
		fmt.Fprintf(b, "<th>%s</th>", esc(name))
	}
	b.WriteString("</tr></thead>\n<tbody>\n")
	htmlMetricsRow(b, "Tokens (in/out)", agentNames, func(name string) string {
		t := agentTotals[name]
		return fmt.Sprintf("%s/%s", formatInt(t.input), formatInt(t.output))
	})
	htmlMetricsRow(b, "Cache (create/read)", agentNames, func(name string) string {
		t := agentTotals[name]
		return fmt.Sprintf("%s/%s", formatInt(t.cacheCreate), formatInt(t.cacheRead))
	})
	htmlMetricsRow(b, "Cache hit rate", agentNames, func(name string) string {
		return fmt.Sprintf("%.1f%%", sr.AgentResults[name].Cache.CacheHitRate*100)
	})
	htmlMetricsRow(b, "Cost USD", agentNames, func(name string) string {
		return fmt.Sprintf("$%.3f", agentTotals[name].cost)
	})
	htmlMetricsRow(b, "Duration", agentNames, func(name string) string {
		return formatDuration(agentTotals[name].duration)
	})
	htmlMetricsRow(b, "Tool calls", agentNames, func(name string) string {
		return fmt.Sprintf("%d", agentTotals[name].toolCalls)
	})
	if hasBudget {
		htmlMetricsRow(b, "Budget", agentNames, func(name string) string {
			ar, ok := sr.AgentResults[name]
			switch {
			case !ok || ar.BudgetResult == nil:
				return "—"
			case ar.BudgetResult.Passed:
				return "PASS"
			default:
				return "FAIL — " + strings.Join(ar.BudgetResult.Violations, "; ")
			}
		})
	}
	b.WriteString("</tbody></table></div>\n")
}

// htmlPerTurnCacheTable renders the per-turn cache breakdown for a multi-turn
// scenario: one row per turn, one cell per agent (in/out · cacheR/cacheW · hit%).
func htmlPerTurnCacheTable(b *strings.Builder, sr ScenarioResult, agentNames []string, maxTurns int) {
	fmt.Fprintf(b, "<details open><summary>Per-turn cache breakdown (%d turns)</summary>\n", maxTurns)
	b.WriteString("<div class=\"tblwrap\"><table>\n<thead><tr><th>Turn</th>")
	for _, name := range agentNames {
		fmt.Fprintf(b, "<th>%s</th>", esc(name))
	}
	b.WriteString("</tr></thead>\n<tbody>\n")
	for turn := 0; turn < maxTurns; turn++ {
		fmt.Fprintf(b, "<tr><th scope=\"row\">%d</th>", turn+1)
		for _, name := range agentNames {
			ar, ok := sr.AgentResults[name]
			if !ok || turn >= len(ar.RunResults) {
				b.WriteString("<td class=\"gap\">—</td>")
				continue
			}
			t := ar.RunResults[turn].Tokens
			total := float64(t.CacheRead + t.CacheCreate + t.InputTokens)
			hit := 0.0
			if total > 0 {
				hit = float64(t.CacheRead) / total
			}
			fmt.Fprintf(b, "<td>%s/%s · %s/%s · %.0f%%</td>",
				formatInt(t.InputTokens), formatInt(t.OutputTokens),
				formatInt(t.CacheRead), formatInt(t.CacheCreate), hit*100)
		}
		b.WriteString("</tr>\n")
	}
	b.WriteString("</tbody></table></div></details>\n")
}

