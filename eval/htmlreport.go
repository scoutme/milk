// htmlAggregateSection renders the cross-scenario aggregates — per-category
// quality, cost-efficiency and the overall winner — with the same accounting
// rules as buildAggregateReport (JudgeError cells excluded from quality
// aggregates; quality/dollar over judged-only cost).
func htmlAggregateSection(b *strings.Builder, scenarioResults []ScenarioResult, agentNames []string) {
	categories := map[string]bool{}
	for _, sr := range scenarioResults {
		categories[sr.Category] = true
	}

	b.WriteString("<section>\n<h2>Aggregate</h2>\n")
	fmt.Fprintf(b, "<p class=\"meta\">Scenarios: %d · Categories: %d · Agents: %d</p>\n",
		len(scenarioResults), len(categories), len(agentNames))

	type agentAccum struct {
		sum   float64
		count int
	}
	sortedCats := sortedKeys(categories)
	catAccums := map[string]map[string]*agentAccum{}
	for _, cat := range sortedCats {
		catAccums[cat] = map[string]*agentAccum{}
		for _, name := range agentNames {
			catAccums[cat][name] = &agentAccum{}
		}
	}
	for _, sr := range scenarioResults {
		for _, name := range agentNames {
			ar, ok := sr.AgentResults[name]
			if !ok || ar.JudgeError != "" {
				continue // unjudged — not a real 0
			}
			acc := catAccums[sr.Category][name]
			acc.sum += ar.WeightedScore
			acc.count++
		}
	}
	overallAccums := map[string]*agentAccum{}
	for _, name := range agentNames {
		overallAccums[name] = &agentAccum{}
	}
	for _, cat := range sortedCats {
		for _, name := range agentNames {
			acc := catAccums[cat][name]
			overallAccums[name].sum += acc.sum
			overallAccums[name].count += acc.count
		}
	}

	// Quality table.
	b.WriteString("<h3>By weighted score (quality)</h3>\n<div class=\"tblwrap\"><table>\n<thead><tr><th></th>")
	for _, name := range agentNames {
		fmt.Fprintf(b, "<th>%s</th>", esc(name))
	}
	b.WriteString("</tr></thead>\n<tbody>\n")
	avgOf := func(acc *agentAccum) float64 {
		if acc.count == 0 {
			return 0
		}
		return acc.sum / float64(acc.count)
	}
	for _, cat := range sortedCats {
		fmt.Fprintf(b, "<tr><th scope=\"row\">%s</th>", esc(cat))
		for _, name := range agentNames {
			fmt.Fprintf(b, "<td>%.1f</td>", avgOf(catAccums[cat][name]))
		}
		b.WriteString("</tr>\n")
	}
	b.WriteString("<tr class=\"weighted\"><th scope=\"row\">Overall</th>")
	for _, name := range agentNames {
		fmt.Fprintf(b, "<td>%.1f</td>", avgOf(overallAccums[name]))
	}
	b.WriteString("</tr>\n</tbody></table></div>\n")

	// Cost-efficiency table.
	b.WriteString("<h3>By cost-efficiency</h3>\n<div class=\"tblwrap\"><table>\n<thead><tr><th></th>")
	for _, name := range agentNames {
		fmt.Fprintf(b, "<th>%s</th>", esc(name))
	}
	b.WriteString("</tr></thead>\n<tbody>\n")
	htmlMetricsRow(b, "Avg cost/scenario", agentNames, func(name string) string {
		var total float64
		n := 0
		for _, sr := range scenarioResults {
			if ar, ok := sr.AgentResults[name]; ok {
				for _, r := range ar.RunResults {
					total += r.CostUSD
				}
				n++
			}
		}
		avg := 0.0
		if n > 0 {
			avg = total / float64(n)
		}
		return fmt.Sprintf("$%.3f", avg)
	})
	htmlMetricsRow(b, "Quality/dollar", agentNames, func(name string) string {
		var totalCost, totalQuality float64
		for _, sr := range scenarioResults {
			if ar, ok := sr.AgentResults[name]; ok && ar.JudgeError == "" {
				for _, r := range ar.RunResults {
					totalCost += r.CostUSD
				}
				totalQuality += ar.WeightedScore
			}
		}
		qpd := 0.0
		if totalCost > 0 {
			qpd = totalQuality / totalCost
		}
		return formatCompactFloat(qpd)
	})
	htmlMetricsRow(b, "Cache hit rate", agentNames, func(name string) string {
		var totalRead, totalCreate, totalInput int64
		for _, sr := range scenarioResults {
			if ar, ok := sr.AgentResults[name]; ok {
				for _, r := range ar.RunResults {
					totalRead += r.Tokens.CacheRead
					totalCreate += r.Tokens.CacheCreate
					totalInput += r.Tokens.InputTokens
				}
			}
		}
		total := float64(totalRead + totalCreate + totalInput)
		hitRate := 0.0
		if total > 0 {
			hitRate = float64(totalRead) / total
		}
		return fmt.Sprintf("%.1f%%", hitRate*100)
	})
	b.WriteString("</tbody></table></div>\n")

	// Winner banner — same tie-break as buildAggregateReport: best judged-only
	// average score, lower total cost on ties.
	if len(agentNames) > 0 {
		bestAgent := agentNames[0]
		bestScore := -1.0
		bestCost := 1e18
		for _, name := range agentNames {
			var score, cost float64
			count := 0
			for _, sr := range scenarioResults {
				if ar, ok := sr.AgentResults[name]; ok && ar.JudgeError == "" {
					score += ar.WeightedScore
					for _, r := range ar.RunResults {
						cost += r.CostUSD
					}
					count++
				}
			}
			avgScore := 0.0
			if count > 0 {
				avgScore = score / float64(count)
			}
			if avgScore > bestScore || (avgScore == bestScore && cost < bestCost) {
				bestScore = avgScore
				bestCost = cost
				bestAgent = name
			}
		}
		runnerUpCost := 0.0
		for _, name := range agentNames {
			if name == bestAgent {
				continue
			}
			var cost float64
			for _, sr := range scenarioResults {
				if ar, ok := sr.AgentResults[name]; ok {
					for _, r := range ar.RunResults {
						cost += r.CostUSD
					}
				}
			}
			if runnerUpCost == 0 || cost < runnerUpCost {
				runnerUpCost = cost
			}
		}
		note := ""
		if bestCost > 0 && runnerUpCost > 0 && runnerUpCost > bestCost {
			note = fmt.Sprintf(" (%.0fx cheaper)", runnerUpCost/bestCost)
		}
		fmt.Fprintf(b, "<p class=\"overall\">Overall winner: <strong>%s</strong>%s</p>\n",
			esc(bestAgent), esc(note))
	}
	b.WriteString("</section>\n")
}

